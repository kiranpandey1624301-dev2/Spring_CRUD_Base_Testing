package com.demo.example.model;

public class Student {
	int id;
	String uname;
	String uphy;
	String uche;
	String umaths;
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getUname() {
		return uname;
	}
	public void setUname(String uname) {
		this.uname = uname;
	}
	public String getUphy() {
		return uphy;
	}
	public void setUphy(String uphy) {
		this.uphy = uphy;
	}
	public String getUche() {
		return uche;
	}
	public void setUche(String uche) {
		this.uche = uche;
	}
	public String getUmaths() {
		return umaths;
	}
	public void setUmaths(String umaths) {
		this.umaths = umaths;
	}
	
	

}
